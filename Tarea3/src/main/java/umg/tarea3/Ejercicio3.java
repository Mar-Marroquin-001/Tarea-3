    private void btnCargarDatosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarDatosActionPerformed
        // TODO add your handling code here:
        
        java.io.File archivo = new java.io.File(rutaArchivo);
    
    // Verificar si el archivo existe en la carpeta temp
    if (!archivo.exists()) {
        javax.swing.JOptionPane.showMessageDialog(this, "No se encontró el archivo: " + rutaArchivo);
        return;
    }

    try (java.util.Scanner sc = new java.util.Scanner(archivo)) {
        indiceTemp = 0;
        
        // Leer línea por línea y llenar el arreglo
        while (sc.hasNextLine() && indiceTemp < 6) {
            String linea = sc.nextLine().trim();
            if (!linea.isEmpty()) {
                temperaturas[indiceTemp] = Double.parseDouble(linea);
                indiceTemp++;
            }
        }
        
        javax.swing.JOptionPane.showMessageDialog(this, "Datos cargados en memoria exitosamente.");
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al leer el archivo: " + e.getMessage());
    }
    }//GEN-LAST:event_btnCargarDatosActionPerformed

    private void btnCalcularEstadisticasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularEstadisticasActionPerformed
        // TODO add your handling code here:
        
        // Validar que se hayan cargado las 6 temperaturas
    if (indiceTemp < 6) {
        javax.swing.JOptionPane.showMessageDialog(this, "Primero debe presionar 'Cargar Datos'.");
        return;
    }

    double suma = 0;
    int diasCalidos = 0;
    int diasFrescos = 0;

    // Recorrer el arreglo para sumar y clasificar
    for (int i = 0; i < temperaturas.length; i++) {
        suma += temperaturas[i];
        
        if (temperaturas[i] >= 25.0) {
            diasCalidos++;
        } else {
            diasFrescos++;
        }
    }

    double promedio = suma / temperaturas.length;

    // Limpiar y mostrar el reporte con el formato solicitado
    txtAreaReporte.setText("Análisis Climático\n");
    txtAreaReporte.append("Promedio de Temperatura: " + Math.round(promedio * 10.0) / 10.0 + "\n");
    txtAreaReporte.append("Días Cálidos (>=25°): " + diasCalidos + "\n");
    txtAreaReporte.append("Días Frescos (<25°): " + diasFrescos + "\n");
    }//GEN-LAST:event_btnCalcularEstadisticasActionPerformed

