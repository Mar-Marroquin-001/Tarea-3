    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        
        
          try {
            String tit = txtTitulo.getText().trim();
            String con = txtConsola.getText().trim();
            int anio = Integer.parseInt(txtAnio.getText().trim());

            if (tit.isEmpty() || con.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.");
                return;
            }

            // Instanciar pasando los parámetros al constructor
            Videojuego nuevo = new Videojuego(tit, con, anio);

            // Agregar a la lista dinámica
            catalogo.add(nuevo);

            JOptionPane.showMessageDialog(this, "Videojuego agregado al catálogo con éxito.");

            // Limpiar cajas de texto
            txtTitulo.setText("");
            txtConsola.setText("");
            txtAnio.setText("");
            txtTitulo.requestFocus();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El año de lanzamiento debe ser un número entero válido.");
        }
    
        
        
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        // TODO add your handling code here:
        
        // Limpiar el área de texto antes de mostrar
        txtAreaInventario.setText("");

        if (catalogo.isEmpty()) {
            txtAreaInventario.setText("El catálogo está vacío actualmente.\n");
            return;
        }

        txtAreaInventario.append("=== INVENTARIO DE VIDEOJUEGOS ===\n\n");

        // Ciclo for para recorrer la lista usando .get(i)
        for (int i = 0; i < catalogo.size(); i++) {
            Videojuego v = catalogo.get(i);
            txtAreaInventario.append((i + 1) + ". Título: " + v.titulo + "\n");
            txtAreaInventario.append("   Consola: " + v.consola + "\n");
            txtAreaInventario.append("   Año: " + v.anioLanzamiento + "\n");
            txtAreaInventario.append("--------------------------------------\n");
        }

        // Cantidad total usando .size()
        txtAreaInventario.append("\nTotal de juegos registrados: " + catalogo.size() + "\n");
        
        
    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        
        // Validar que la lista no esté vacía (tamaño mayor a 0)
        if (catalogo.size() > 0) {
            int ultimoIndice = catalogo.size() - 1;
            Videojuego eliminado = catalogo.remove(ultimoIndice);

            JOptionPane.showMessageDialog(this, "Se eliminó el último juego: " + eliminado.titulo);
        } else {
            JOptionPane.showMessageDialog(this, "No hay videojuegos en el catálogo para eliminar.");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

