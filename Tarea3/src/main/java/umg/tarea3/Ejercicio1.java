    private void btnRegistrarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarVentaActionPerformed
        // TODO add your handling code here:
        if (indiceVentas < 5) {
        try {
            // Leer el número ingresado en la caja de texto
            double monto = Double.parseDouble(txtMonto.getText().trim());
            
            // Guardarlo en la posición actual del arreglo
            ventas[indiceVentas] = monto;
            indiceVentas++;
            
            // Limpiar la caja para la siguiente venta
            txtMonto.setText("");
            txtMonto.requestFocus();
            
            javax.swing.JOptionPane.showMessageDialog(this, "Venta " + indiceVentas + " registrada exitosamente.");
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor ingrese un monto numérico válido.");
        }
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Ya completó las 5 ventas de la semana.");
    }
        
        
        
        
    }//GEN-LAST:event_btnRegistrarVentaActionPerformed

