    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
        // TODO add your handling code here:
        
        if (indiceVentas < 5) {
        javax.swing.JOptionPane.showMessageDialog(this, "Debe registrar las 5 ventas antes de generar el reporte.");
        return;
    }

    double totalVendido = 0;
    int ventasSuperiores500 = 0;

    // Recorrer el arreglo para sumar y contar
    for (int i = 0; i < ventas.length; i++) {
        totalVendido += ventas[i];
        if (ventas[i] > 500.0) {
            ventasSuperiores500++;
        }
    }

    // Crear la carpeta temp si no existe
    java.io.File carpeta = new java.io.File("temp");
    if (!carpeta.exists()) {
        carpeta.mkdirs();
    }

    // Escribir el reporte en el archivo de texto
    try (java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter("temp/MarlynM_reporte_ventas.txt"))) {
        pw.println("Reporte de Ventas");
        pw.println("Total Vendido: " + totalVendido);
        pw.println("Ventas superiores a Q500: " + ventasSuperiores500);
        
        javax.swing.JOptionPane.showMessageDialog(this, "Reporte generado en temp/MarlynM_reporte_ventas.txt");
    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el archivo: " + e.getMessage());
    }
        
    }//GEN-LAST:event_btnGenerarReporteActionPerformed

