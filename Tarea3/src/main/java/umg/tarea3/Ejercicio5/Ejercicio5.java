    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
        // TODO add your handling code here:
        
        try {
            String nom = txtNombreArtista.getText().trim();
            String pais = txtPaisArtista.getText().trim();
            int oyentes = Integer.parseInt(txtOyentesArtista.getText().trim());

            if (nom.isEmpty() || pais.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos del artista.");
                return;
            }

            // Instanciar y guardar datos del artista
            Artista a = new Artista();
            a.nombre = nom;
            a.paisOrigen = pais;
            a.oyentesMensuales = oyentes;

            // Guardar en la variable general para que la canción lo pueda usar
            this.artistaActual = a;

            // Mostrar el nombre automáticamente en el campo de la canción
            txtArtistaCancion.setText(a.nombre);

            // Bitácora
            txtAreaBitacora.append("--- ARTISTA REGISTRADO ---\n");
            txtAreaBitacora.append("Nombre: " + a.nombre + "\n");
            txtAreaBitacora.append("País: " + a.paisOrigen + "\n");
            txtAreaBitacora.append("Oyentes mensuales: " + a.oyentesMensuales + "\n\n");

            // Limpiar campos del artista
            txtNombreArtista.setText("");
            txtPaisArtista.setText("");
            txtOyentesArtista.setText("");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El número de oyentes debe ser un valor numérico entero.");
        }
        
        
        
        
    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
        // TODO add your handling code here:
        
        
        
try {
    String tit = txtTituloCancion.getText().trim();
    String nomArtista = txtArtistaCancion.getText().trim();
    int dur = Integer.parseInt(txtDuracionCancion.getText().trim());
    String gen = txtGeneroCancion.getText().trim();

    if (tit.isEmpty() || nomArtista.isEmpty() || gen.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos de la canción.");
        return;
    }

    Cancion c = new Cancion();
    c.titulo = tit;
    c.nombreArtista = nomArtista;
    c.duracionSegundos = dur;
    c.genero = gen;

    txtAreaBitacora.append("--- CANCIÓN REGISTRADA ---\n");
    txtAreaBitacora.append("Título: " + c.titulo + "\n");
    txtAreaBitacora.append("Artista: " + c.nombreArtista + "\n");
    txtAreaBitacora.append("Duración: " + c.duracionSegundos + " seg\n");
    txtAreaBitacora.append("Género: " + c.genero + "\n\n");

    txtTituloCancion.setText("");
    txtArtistaCancion.setText("");
    txtDuracionCancion.setText("");
    txtGeneroCancion.setText("");

    txtTituloCancion.requestFocus();

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "La duración debe ser un número entero.");
}

        
    }//GEN-LAST:event_btnCrearCancionActionPerformed

