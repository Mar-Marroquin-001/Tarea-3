    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String buscado = txtBuscarAlbum.getText().trim();
        
        if (buscado.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor escribe el nombre de un álbum.");
            return;
        }

        boolean encontrado = false;

        // Aquí sí existe la variable i dentro del ciclo for:
        for (int i = 0; i < titulos.length; i++) {
            if (titulos[i] != null && titulos[i].equalsIgnoreCase(buscado)) {
                lblAnioActual.setText(String.valueOf(anios[i]));
                encontrado = true;
                break;
            }
        }

        if (!encontrado) {
            lblAnioActual.setText("");
            javax.swing.JOptionPane.showMessageDialog(this, "El álbum '" + buscado + "' no fue encontrado.");
        }
        
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarRegistroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarRegistroActionPerformed
        // TODO add your handling code here:
        
        
        String buscado = txtBuscarAlbum.getText().trim();
    String nuevoAnioStr = txtNuevoAnio.getText().trim();

    if (buscado.isEmpty() || nuevoAnioStr.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Debe ingresar el álbum y el nuevo año.");
        return;
    }

    try {
        int nuevoAnio = Integer.parseInt(nuevoAnioStr);
        int indiceEncontrado = -1;

        // Buscar el índice del disco a modificar
        for (int i = 0; i < titulos.length; i++) {
            if (titulos[i] != null && titulos[i].equalsIgnoreCase(buscado)) {
                indiceEncontrado = i;
                break;
            }
        }

        if (indiceEncontrado != -1) {
            // Actualizar en el arreglo en memoria
            anios[indiceEncontrado] = nuevoAnio;

            // Sobrescribir el archivo discos.csv en modo false
            try (java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter(rutaCSV, false))) {
                for (int i = 0; i < titulos.length; i++) {
                    pw.println(titulos[i] + "," + anios[i]);
                }
                
                lblNuevoAnio.setText("Año actual: " + nuevoAnio);
                txtNuevoAnio.setText("");
                javax.swing.JOptionPane.showMessageDialog(this, "¡Registro actualizado exitosamente en el archivo!");
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró el álbum para actualizar.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "El año debe ser un número entero válido.");
    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el archivo: " + e.getMessage());
    }
    }//GEN-LAST:event_btnActualizarRegistroActionPerformed

