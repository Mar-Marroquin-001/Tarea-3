    // Método que lee el CSV con Scanner y .split(",")
    private void cargarDiscos() {
        java.io.File archivo = new java.io.File(rutaCSV);
        if (!archivo.exists()) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró el archivo: " + rutaCSV);
            return;
        }

        try (java.util.Scanner sc = new java.util.Scanner(archivo)) {
            int i = 0;
            while (sc.hasNextLine() && i < 5) {
                String linea = sc.nextLine().trim();
                if (!linea.isEmpty()) {
                    String[] partes = linea.split(",");
                    titulos[i] = partes[0].trim();
                    anios[i] = Integer.parseInt(partes[1].trim());
                    i++;
                }
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar discos: " + e.getMessage());
        }
    }
    

