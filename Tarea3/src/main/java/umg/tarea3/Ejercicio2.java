    private void btnRegistrarAsistenteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarAsistenteActionPerformed
        // TODO add your handling code here:
        
        if (indiceAsistentes < 5) {
        String nombre = txtNombreAsistente.getText().trim();
        
        // Validar que no dejen la caja vacía
        if (nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor ingrese el nombre del asistente.");
            return;
        }

        // Guardar en el arreglo
        asistentes[indiceAsistentes] = nombre;
        indiceAsistentes++;

        // Mostrar en el área de texto (pantalla grande)
        txtAreaAsistencia.append(indiceAsistentes + ". " + nombre + "\n");

        // Limpiar la caja de texto y enfocar
        txtNombreAsistente.setText("");
        txtNombreAsistente.requestFocus();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Ya se registraron los 5 asistentes.");
    }
        
        
    }//GEN-LAST:event_btnRegistrarAsistenteActionPerformed

    private void btnExportarListaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarListaActionPerformed
        // TODO add your handling code here:
        
        // Validar que ya estén los 5 registrados
    if (indiceAsistentes < 5) {
        javax.swing.JOptionPane.showMessageDialog(this, "Debe registrar a los 5 asistentes antes de exportar.");
        return;
    }

    // Asegurar que exista la carpeta temp
    java.io.File carpeta = new java.io.File("temp");
    if (!carpeta.exists()) {
        carpeta.mkdirs();
    }

    // Escribir la lista en el archivo
    try (java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter("temp/MarlynM_asistencia.txt"))) {
        pw.println("Lista de Asistencia");
        for (int i = 0; i < asistentes.length; i++) {
            pw.println((i + 1) + ". " + asistentes[i]);
        }
        javax.swing.JOptionPane.showMessageDialog(this, "Lista exportada con éxito en temp/MarlynM_asistencia.txt");
    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al exportar: " + e.getMessage());
    }
        
    }//GEN-LAST:event_btnExportarListaActionPerformed

